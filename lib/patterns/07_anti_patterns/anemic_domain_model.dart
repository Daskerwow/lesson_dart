/// ============================================================================
/// АНТИПАТТЕРН: ANEMIC DOMAIN MODEL (Анемичная доменная модель)
/// ============================================================================
///
/// ПРОБЛЕМА:
/// Доменные классы содержат ТОЛЬКО данные (геттеры/сеттеры) без какого-либо
/// поведения — вся бизнес-логика вынесена наружу, в отдельные "Service"-
/// классы, которые манипулируют полями доменного объекта напрямую. Мартин
/// Фаулер называет это "анти-паттерном" объектно-ориентированного дизайна:
/// объекты превращаются в "мешки с геттерами/сеттерами" (data bags),
/// а вся логика живёт в процедурных сервисах — по сути, это процедурный
/// стиль, притворяющийся объектно-ориентированным.
///
/// ОТЛИЧИЕ ОТ DTO: DTO (см. 06_enterprise/dto.dart) — это нормально,
/// т.к. DTO ПРЕДНАЗНАЧЕН для передачи данных и не должен иметь поведения.
/// Проблема — когда доменная сущность (Entity), которая ДОЛЖНА защищать
/// свои инварианты, вырождается в подобие DTO.
///
/// ПОЧЕМУ ЭТО ПЛОХО:
/// - Бизнес-правила размазаны по множеству сервисов — одно и то же
///   правило легко продублировать в двух местах (и забыть обновить оба).
/// - Объект не может гарантировать свою внутреннюю согласованность —
///   любой внешний код может привести его в невалидное состояние
///   напрямую через сеттер, минуя проверки.
/// - Теряется весь смысл инкапсуляции ООП.
///
/// ГДЕ УМЕСТНО (не всегда антипаттерн!): для очень простых CRUD-приложений
/// без сложной бизнес-логики анемичная модель — нормальный, прагматичный
/// выбор. Проблема возникает именно в БОГАТОЙ бизнес-логике, вынесенной
/// наружу без необходимости. Сравните с "богатой" моделью в ddd.dart.
library;

// ============================================================================
// ПЛОХО: анемичная модель — только данные, вся логика "снаружи".
// ============================================================================
class BankAccountAnemic(
  final String id,
  var double balance, {
  var bool isFrozen = false,
});

/// Вся бизнес-логика живёт в сервисе и манипулирует полями напрямую —
/// НИЧТО не мешает другому месту в коде забыть проверку isFrozen
/// и напрямую изменить balance, нарушив инвариант.
class BankAccountServiceAnemic {
  void withdraw(BankAccountAnemic account, double amount) {
    // Проверка бизнес-правила размазана по сервису, а не живёт
    // внутри самого объекта, который должен её defend'ить.
    if (account.isFrozen) {
      throw StateError('Счёт заморожен');
    }
    if (amount > account.balance) {
      throw StateError('Недостаточно средств');
    }
    account.balance -= amount; // прямая мутация поля извне!
  }

  void deposit(BankAccountAnemic account, double amount) {
    if (account.isFrozen) {
      throw StateError('Счёт заморожен');
    }
    account.balance += amount;
  }
}

// ============================================================================
// РЕФАКТОРИНГ: "богатая" доменная модель (Rich Domain Model) — данные
// и поведение живут ВМЕСТЕ, объект сам защищает свои инварианты.
// Сравните с DDD-примером в 04_architectural/ddd.dart.
// ============================================================================
class BankAccountRich(final String id, double initialBalance) {
  double _balance = initialBalance;
  bool _isFrozen;

  this : _isFrozen = false;

  double get balance => _balance; // только чтение снаружи

  /// Бизнес-логика инкапсулирована ВНУТРИ объекта — невозможно снять
  /// деньги с замороженного счёта или уйти в минус, минуя эту проверку,
  /// т.к. balance не имеет публичного сеттера.
  void withdraw(double amount) {
    if (_isFrozen) {
      throw StateError('Счёт заморожен, операции недоступны');
    }
    if (amount > _balance) {
      throw StateError(
        'Недостаточно средств: баланс $_balance, запрошено $amount',
      );
    }
    _balance -= amount;
  }

  void deposit(double amount) {
    if (_isFrozen) {
      throw StateError('Счёт заморожен, операции недоступны');
    }
    if (amount <= 0) {
      throw ArgumentError('Сумма пополнения должна быть положительной');
    }
    _balance += amount;
  }

  void freeze() => _isFrozen = true;
  void unfreeze() => _isFrozen = false;
}

void main() {
  print('--- Анемичная модель ---');
  final anemicAccount = BankAccountAnemic('acc1', 100);
  final service = BankAccountServiceAnemic();
  service.withdraw(anemicAccount, 30);
  print('Баланс: ${anemicAccount.balance}');
  // Ничто не мешает сделать так, полностью обойдя бизнес-правила:
  anemicAccount.balance = -9999; // невалидное состояние никак не защищено!
  print('Баланс после "прямого взлома": ${anemicAccount.balance}');

  print('\n--- Богатая доменная модель ---');
  final richAccount = BankAccountRich('acc2', 100);
  richAccount.withdraw(30);
  print('Баланс: ${richAccount.balance}');
  try {
    richAccount.freeze();
    richAccount.withdraw(10); // защищено самим объектом
  } on StateError catch (e) {
    print('Операция отклонена (как и должно быть): $e');
  }
}
