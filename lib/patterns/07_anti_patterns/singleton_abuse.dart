/// ============================================================================
/// АНТИПАТТЕРН: SINGLETON ABUSE (Злоупотребление одиночкой)
/// ============================================================================
///
/// ПРОБЛЕМА:
/// Singleton (см. 01_creational/singleton.dart) — легитимный паттерн, но
/// его ЧРЕЗМЕРНОЕ и НЕОСТОРОЖНОЕ применение превращается в антипаттерн:
/// глобальное изменяемое состояние, к которому обращаются из любой точки
/// программы напрямую (`MyGlobalThing.instance.doSomething()`), вместо
/// явной передачи зависимости.
///
/// ПОЧЕМУ ЭТО ПЛОХО:
/// - Скрытые зависимости: глядя на сигнатуру класса/метода, невозможно
///   понять, что он тайно использует глобальный Singleton — зависимости
///   не видны в конструкторе, "спрятаны" внутри методов.
/// - Невозможность тестирования в изоляции: Singleton хранит состояние
///   МЕЖДУ тестами (если не сбрасывать вручную), тесты начинают влиять
///   друг на друга непредсказуемым образом.
/// - Невозможность иметь несколько независимых экземпляров, когда это
///   вдруг понадобилось (например, мультитенантное приложение, где нужна
///   отдельная "сессия" на каждого пользователя).
/// - Плотная связанность всего кода с одной глобальной точкой — рефакторинг
///   становится опасным, т.к. неясно, кто и как использует Singleton.
///
/// КАК РАСПОЗНАТЬ: конструкторы классов без параметров, но внутри —
/// множество обращений вида `SomeSingleton.instance.xxx`.
library;

// ============================================================================
// ПЛОХО: "глобальная свалка состояния" через Singleton, к которому
// обращаются откуда угодно — типичный "Service Locator" антипаттерн,
// часто сопутствующий злоупотреблению Singleton.
// ============================================================================
class GlobalAppState._() {
  static final GlobalAppState instance = GlobalAppState._();

  String? currentUserId;
  double cartTotal = 0;
  List<String> cartItems = [];
  bool isDarkTheme = false;
  Map<String, dynamic> sessionCache = {};
}

/// Любой класс в приложении может незаметно обратиться к глобальному
/// состоянию — эта зависимость НЕВИДИМА в сигнатуре класса.
class CheckoutServiceBad {
  // Обратите внимание: конструктор пустой! Но метод ниже тайно тянет
  // зависимость из глобального Singleton — при взгляде на класс снаружи
  // непонятно, что ему вообще нужен GlobalAppState.
  double calculateTotal() {
    final total = GlobalAppState.instance.cartTotal;
    if (GlobalAppState.instance.currentUserId == null) {
      throw StateError('Пользователь не авторизован');
    }
    return total;
  }
}

// ============================================================================
// РЕФАКТОРИНГ: явная передача состояния через конструктор (Dependency
// Injection, см. 06_enterprise/dependency_injection.dart). Зависимости
// видны СНАРУЖИ класса — по сигнатуре конструктора сразу понятно, что нужно.
// ============================================================================

/// Вместо глобального мутабельного состояния — явная, неизменяемая
/// модель корзины, передаваемая туда, где она нужна.
class const Cart({
  required final List<String> items,
  required final double total,
});

class const UserSession(final String userId);

class CheckoutServiceGood({
  required final Cart cart,
  required final UserSession session,
}) {
  double calculateTotal() {
    // Никакого обращения к глобальному Singleton — все данные уже здесь.
    return cart.total;
  }
}

void main() {
  print('--- Плохо: скрытая зависимость от Singleton ---');
  GlobalAppState.instance.currentUserId = 'user_1';
  GlobalAppState.instance.cartTotal = 150.0;
  final badService = CheckoutServiceBad(); // конструктор "пустой", но обманчив
  print('Итого (bad): ${badService.calculateTotal()}');

  print('\n--- Хорошо: явные, тестируемые зависимости ---');
  final goodService = CheckoutServiceGood(
    cart: const Cart(items: ['sku1', 'sku2'], total: 150.0),
    session: const UserSession('user_1'),
  );
  print('Итого (good): ${goodService.calculateTotal()}');

  // В юнит-тесте для CheckoutServiceGood достаточно создать новый Cart —
  // никакого сброса глобального состояния между тестами не требуется.
}
